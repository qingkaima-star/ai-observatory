//  跨页复用的**读数口径措辞**，唯一出处。
//
//  为什么要单独立一个文件：同一个「服务端匹配总数」在五页里出现过四种说法
//  （`SessionsView` 的「服务端匹配总数 · 与分页无关」、`CommandsView` 的
//  「服务端匹配总数 · 已加载 N 条」、`FilesView` 的「服务端匹配 N 条」、
//  `TimelineView` 的「服务端匹配总数，且已全部加载到本页。」）。
//  措辞分叉本身不是缺陷，**它是缺陷的载体**：那句「且已全部加载到本页」
//  只在真的全加载时才成立，写在 caption 里就等于让同一句文案有两种真假——
//  总控 2026-09-21 定全站口径时把它点名禁掉。
//
//  收成一个常量之后，改口径是一处，五页跟着走；写用例时也只需钉一个字符串。
//

import Foundation

/// 跨页复用的读数口径措辞。新增一条之前先问：这句话是不是**每一页**都该这么说？
/// 只有一页用的口径写在该页自己的文件里（如 `Performance/SelfProcessOverheadPanel.swift`
/// 的 `SelfProcessOverheadCopy`），别往这里堆。
enum ReadoutCopy {

    /// hero 大数下面那句口径说明：那个数是服务端按当前查询算出的总数，
    /// **与本地加载了多少无关**。
    ///
    /// ⚠️ 这句里不许出现「已全部加载」「还有 N 条没加载」这类**只在特定分页状态下为真**的话：
    /// 分页状态变了而文案没跟着变，就是界面在说谎。加载了多少由列表标题行那句
    /// 「已加载 M / 共 N」说（那是操作语义位点，全站口径允许的第二处）。
    static let serverTotalCaption = "服务端匹配总数 · 与分页无关"
}
